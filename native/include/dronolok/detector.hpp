    int stuck_base = 12;
    float stuck_steady = 0.7f;
    float stuck_px = 3.f;
    float stuck_travel = 8.f;
    float stuck_r = 6.f;
    int stuck_hold = 50;
    float stuck_heat = 0.1f;
