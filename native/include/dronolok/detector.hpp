    bool hard_switch_follow = true;
    // ...и на цель, которую камера не ведёт, но вдвое медленнее (false — нет): жёсткий захват на
    // летящем дроне уходил на медленный второй дрон, как только тот набирал вес (wt3 к. 186, wt5
    // к. 396); просьба Maxim 30.10 — с дрона на дрон не переходить
    bool hard_switch_slow = false;
    // Дрейф фона. Камера медленно поворачивается или дрожит в руке (прицел в игре плывёт, съёмка с
    // рук), сдвиг за кадр меньше, чем замечает оценка поворота камеры, и всё неподвижное — верхушка
    // вышки, столб, кончики крон — плывёт по кадру вместе с фоном, как медленная цель, а с lock_slow
    // такая цель для захвата ещё и весомее летящего дрона (wt16 на 14 к/с: захват на верхушке вышки).
    // Дрейф — медиана скорости устоявшихся треков (их большинство — неподвижные предметы), если таких
    // треков не меньше drift_tracks и дрейф быстрее drift_min пикс./кадр при 25 к/с. Пока он есть, для
    // захвата пробег и скорость цели считаются относительно фона: плывущее с фоном весит как
    // зависшее, жёсткий захват на нём не держится, новый захват (lock_mover) — только на трек,
    // пролетевший относительно фона дальше mover_px. Обнаружение и класс цели не меняются. 0 — выкл.
    // Ночной тест 30.10: wt16 на 14 к/с 0 -> 98% (фаза 0), на 60 к/с 92 -> 94%, прочие ролики без изменений
    float drift_min = 0.25f;
    int drift_tracks = 5;
    // скорость трека для дрейфа — по стольким последним попаданиям при 25 к/с (не меньше 8; во времени:
    // на 60 к/с 8 попаданий — 0.13 с, шум положения отклика того же порядка, что и сам дрейф)
    int drift_obs = 13;
