    bool lock_mover = false;
    float lock_mover_fps = 31.f;
    // Захваченная цель остаётся в выдаче, пока трек жив: подтверждённый раньше, с новой отметкой он
    // надёжен, хоть попаданий в окне и меньше confirm. Дрон в дымке виден через кадр-два, и трек
    // пропадал из выдачи, а жёсткий захват 1-2 с держался на том, чего нет (wt24, 547-618)
    bool lock_solid = true;
