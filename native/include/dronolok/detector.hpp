    // stuck_obs попаданий (кадров при 25 к/с) при неподвижной камере стоит по сцене на месте — не дальше stuck_px
    // от последнего (отклик предмета скачет по сетке 2 пикс.), — хотя с прежней скоростью ушёл бы за это время
    // дальше stuck_travel пикс. и вчетверо дальше разброса стоянки.
    // Это дрон залетел за дерево, крону, столб или за кромку леса, а трек подхватил неподвижный отклик предмета:
    // захват (и жёсткий) стоял на нём секундами (wt11 60 к/с к. 457–627). Такой трек возвращается на прогноз с
    // прежней скоростью, а место — «предмет»: stuck_r пикс. вокруг (x2 на каждом грубом масштабе), пока там есть
