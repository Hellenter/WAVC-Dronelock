    // (ведомый камерой и точка спокойного неба — сразу). Иначе захват (мягкий) садится на первый
    // подтверждённый блик листвы. Ролики без дронов, кадров с захватом: 15 к/с 43 -> 9%, 60 к/с 26 -> 10%;
