    // Это ветки ближних деревьев на повороте камеры: оценка поворота по дальнему фону, и они «летят»
    // 900-1900 пикс./с (записи без дронов wt20, wt23 на 60 к/с: 15-30 пикс./кадр). Дроны в разметке
    // в захвате — не быстрее 7 пикс./кадр на 60 к/с (420 пикс./с). 24 — 600 пикс./с, 10 пикс./кадр на 60 к/с
    float lock_speed_max = 24.f;
    // Новый захват — только на трек, набравший cls_min_hits попаданий (ведомый камерой и точка
    // спокойного неба — сразу), на любой частоте; lock_mover вдобавок требует, чтобы он летал.
    // На 60 к/с захват брал третье попадание блика в начале ролика, пока маска и карта помех
    // не обучены (n1: 26% кадров), а дрон ждёт лишь 5 кадров (0.08 с). Вместе с lock_speed_max ролики
    // без дронов на 60 к/с 13.2 -> 2.7% кадров с захватом, на дроне 88.6 -> 89.0% (30.10)
    bool lock_established = true;
