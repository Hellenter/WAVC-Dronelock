    // дрона на медленную птицу рядом, вес которой с lock_slow выше. Цель, за которой идёт камера
    // (followed), можно и «птицей»: на 60 к/с wt17 настоящий дрон считался птицей
    bool hard_switch_drone = true;
    // ...и на цель, которую ведёт камера (followed), — без условия "вдвое медленнее": её скорость по
    // сцене — это скорость камеры. Иначе жёсткий захват, севший до того на землю или второй самолёт,
