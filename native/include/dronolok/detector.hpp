    // раз — переход сразу. Новый захват (lock_mover) садился на пролетевшую птицу раньше, чем дрон набирал
    // попаданий, и выдержка (на 60 к/с 29 кадров, счёт с утечкой, вес скачет) держала его на птице секунду (wt16)
