    // последней скорости не меньше чем на долю stuck_steady пути с ней (0 — не проверять). Иначе это не полёт,
    // а трек, скачущий по откликам листвы или блика: в первые секунды ролика их «останавливало» десятками, и на
    // прогнозе со «скоростью» прыжка такой трек держал захват вместо дрона (wt3, wt7 на 14 к/с: доля 0.4–0.67;
