// Дронолок: подстройка алгоритма под железо.
//
// Профили — готовые наборы блоков алгоритма от "всё включено" до "минимум" для
// слабого устройства. Регулятор нагрузки (LoadGovernor) на ходу упрощает работу,
// если кадры не успевают обрабатываться в темпе камеры, и возвращает обратно,
// когда запас появился. Калибровка — эталонный замер скорости ядра CPU, одинаковый
// на ПК и на Raspberry Pi: по отношению этих чисел оценивается, во сколько раз
// устройство медленнее ПК.
#pragma once
#include "dronolok/detector.hpp"

namespace dronolok {

// Блоки алгоритма, которые можно включать и выключать
struct AlgoBlocks {
    int scales = 0;            // масштабов: 1 — только дальние точки, до 4 — близкий крупный дрон; 0 — не трогать (авто)
    bool motion = true;        // учёт движения камеры (GlobalMotion): съёмка с рук, поворотка
    bool zones = true;         // зоны кадра небо / земля / кромка
    bool skyMask = true;       // маска неба по первым кадрам (неподвижная камера)
    bool staticMemory = true;  // долгая память статичных помех (неподвижная камера)
    bool bothPolarities = true;// искать и тёмные, и яркие цели (иначе только тёмные — вдвое дешевле)
    int fullEvery = 1;         // весь кадр раз в N кадров, между ними — только вокруг целей
    int coarseEvery = 2;       // крупные масштабы раз в N кадров
    float resolution = 1.f;    // доля разрешения кадра для обработки (масштабирует вызывающий код)
};

enum class Profile { Full = 0, Balanced = 1, Economy = 2, Minimal = 3 };
const char* profile_name(Profile p);   // по-русски
AlgoBlocks profile_blocks(Profile p);

// Перенести блоки в настройки детектора и трекера. motion, skyMask и resolution
// исполняет вызывающий код (оценка движения камеры, маска неба и масштаб кадра — вне детектора).
void apply_blocks(const AlgoBlocks& b, DetectorConfig& d, TrackerConfig& t);

// Регулятор нагрузки: держит обработку кадра в бюджете (период кадров камеры).
// Ступени (каждая включает предыдущие):
//   1 — крупные масштабы раз в 2 кадра;   2 — весь кадр раз в 2 кадра;
//   3 — крупные масштабы раз в 4 кадра;   4 — весь кадр раз в 3 кадра, не больше 2 масштабов;
//   5 — весь кадр раз в 4 кадра, 1 масштаб.
// Упрощает, когда среднее время кадра выше 90% бюджета; возвращает, когда ниже 50%.
class LoadGovernor {
public:
    static constexpr int MAX_LEVEL = 5;
    // ms — время обработки кадра (всего: движение камеры, детектор, трекер), budgetMs — период кадров.
    // true — ступень поменялась, настройку надо применить заново (apply)
    bool update(double ms, double budgetMs);
    int level() const { return level_; }
    double average() const { return avg_; }
    void reset();
    // Ступень level поверх базовой настройки детектора
    static void apply(int level, DetectorConfig& d);
    static const char* describe(int level);   // что упрощено, по-русски

private:
    int level_ = 0, since_ = 0;
    double avg_ = 0;
    bool init_ = false;
};

// Эталонный замер: мс на 1 Мп кадра — один поток, 128-битный SIMD (SSE2 на x86,
// NEON на ARM, иначе скалярный), один масштаб, обе полярности, синтетическое небо
// с целями. runs — число повторов, берётся медиана. Занимает ~0.1-2 с.
double calibrate_ms_per_mp(int runs = 31);

}  // namespace dronolok
